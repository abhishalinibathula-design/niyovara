export function matchClauseKey(title: string, text = ""): string {
  const normTitle = title.toLowerCase().trim();
  const normText = text.toLowerCase();

  if (normTitle.includes("accepting warranty") || normTitle.includes("additional liability")) {
    return "accepting warranty or additional liability";
  }
  if (normTitle.includes("late payment") || normTitle.includes("penalty") || normTitle.includes("late fee")) {
    return "late payment penalty";
  }
  if (normTitle.includes("copyright") || normText.includes("copyright license")) {
    return "grant of copyright license";
  }
  if (normTitle.includes("patent") || normText.includes("patent license")) {
    return "grant of patent license";
  }
  if (normTitle.includes("redistribut") || normText.includes("redistribution")) {
    return "redistribution";
  }
  if (normTitle.includes("contribution") || normText.includes("submission of contribution")) {
    return "submission of contributions";
  }
  if (normTitle.includes("trademark") || normTitle.includes("trade name")) {
    return "trademarks";
  }
  if (normTitle.includes("disclaimer") || normTitle.includes("warranty") || normText.includes("as is")) {
    return "disclaimer of warranty";
  }
  if (normTitle.includes("liabilit") || normText.includes("limitation of liability")) {
    return "limitation of liability";
  }
  if (normTitle.includes("definition") || normText.includes("shall mean")) {
    return "definitions";
  }
  if (normTitle.includes("service") || normText.includes("maintenance service")) {
    return "services";
  }
  if (normTitle.includes("payment") || (normText.includes("pay") && normText.includes("invoice"))) {
    return "payment";
  }
  if (normTitle.includes("terminat") || normText.includes("terminate this agreement")) {
    return "termination";
  }
  if (normTitle.includes("term") || normText.includes("expires on")) {
    return "term";
  }
  if (normTitle.includes("confident") || normText.includes("keep all data")) {
    return "confidentiality";
  }
  if (normTitle.includes("exception") || normTitle.includes("force majeure") || normText.includes("natural disaster")) {
    return "exceptions";
  }
  if (normTitle.includes("indemnif")) {
    return "indemnification";
  }
  if (normTitle.includes("governing law") || normTitle.includes("jurisdiction")) {
    return "governing law";
  }
  if (normTitle.includes("dispute") || normTitle.includes("arbitrat")) {
    return "dispute resolution";
  }
  return "";
}

