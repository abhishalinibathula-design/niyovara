export function getClauseFallbackTranslation(c: Clause, lang: string): string | null {
  if (lang === "English") return null;
  const langDict = FULL_CLAUSE_TRANSLATIONS[lang];
  if (!langDict) return summarizeClause(c, lang);

  const matchedKey = matchClauseKey(c.title, c.text);
  if (matchedKey && langDict[matchedKey]) {
    return langDict[matchedKey];
  }

  const normTitle = c.title.toLowerCase().trim();
  const directKey = `${c.id}:${normTitle}`;
  if (langDict[directKey]) {
    return langDict[directKey];
  }

  return summarizeClause(c, lang);
}

export function getAskFallbackAnswer(hits: Clause[], lang: string): string {
  const headers = getSectionHeaders(lang);
  if (!hits.length) {
    return headers.notFound;
  }
  return hits
    .map(c => {
      const translation = getClauseFallbackTranslation(c, lang);
      const summary = summarizeClause(c, lang);
      const clauseLabel =
        lang === "Telugu"
          ? `[క్లాజు ${c.id} — ${c.title}]`
          : lang === "Hindi"
          ? `[धारा ${c.id} — ${c.title}]`
          : lang === "Tamil"
          ? `[பிரிவு ${c.id} — ${c.title}]`
          : lang === "Kannada"
          ? `[ಷರತ್ತು ${c.id} — ${c.title}]`
          : lang === "Malayalam"
          ? `[ക്ലോസ് ${c.id} — ${c.title}]`
          : lang === "Marathi"
          ? `[कलम ${c.id} — ${c.title}]`
          : lang === "Bengali"
          ? `[ধারা ${c.id} — ${c.title}]`
          : `[Clause ${c.id} — ${c.title}]`;
      return `${clauseLabel}: ${translation || summary || c.text}`;
    })
    .join("\n\n");
}
